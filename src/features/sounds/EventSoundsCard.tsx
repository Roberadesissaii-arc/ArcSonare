import {
  BellIcon,
  CheckIcon,
  CloseIcon,
  HelpIcon,
  MicIcon,
  SparkleIcon,
  VolumeIcon,
  WarningIcon,
  WaveIcon,
} from "../../components/Icons";
import type { SoundEvent } from "../../config/prefs";
import { EVENT_SOUND_UI } from "./soundEventRegistry";
import { EventSoundRow } from "./EventSoundRow";
import { SoundSettingsCard } from "./SoundSettingsCard";

const ICONS: Record<SoundEvent, React.ReactNode> = {
  "overlay-open": <MicIcon size={14} />,
  "overlay-close": <CloseIcon size={14} />,
  listening: <WaveIcon size={14} />,
  thinking: <SparkleIcon size={14} />,
  responding: <VolumeIcon size={14} />,
  "task-completed": <CheckIcon size={14} />,
  confirmation: <HelpIcon size={14} />,
  error: <WarningIcon size={14} />,
  notification: <BellIcon size={14} />,
  "wake-word": <WaveIcon size={14} />,
};

interface EventSoundsCardProps {
  masterEnabled: boolean;
  events: Record<SoundEvent, { enabled: boolean; volume: number }>;
  currentlyPreviewing: SoundEvent | null;
  onToggle: (id: SoundEvent, enabled: boolean) => void;
  onVolume: (id: SoundEvent, volume: number) => void;
  onPreview: (id: SoundEvent) => void;
}

export function EventSoundsCard({
  masterEnabled,
  events,
  currentlyPreviewing,
  onToggle,
  onVolume,
  onPreview,
}: EventSoundsCardProps) {
  const left = EVENT_SOUND_UI.filter((e) => e.column === "left");
  const right = EVENT_SOUND_UI.filter((e) => e.column === "right");

  const renderCol = (items: typeof left) =>
    items.map((event) => {
      const pref = events[event.id] ?? { enabled: true, volume: 70 };
      return (
        <EventSoundRow
          key={event.id}
          id={event.id}
          name={event.displayName}
          icon={ICONS[event.id]}
          enabled={pref.enabled}
          volume={pref.volume}
          masterEnabled={masterEnabled}
          previewing={currentlyPreviewing === event.id}
          onToggle={(enabled) => onToggle(event.id, enabled)}
          onVolume={(volume) => onVolume(event.id, volume)}
          onPreview={() => onPreview(event.id)}
        />
      );
    });

  return (
    <SoundSettingsCard
      icon={<BellIcon size={15} />}
      title="Event sounds"
      description="Each event can be enabled and adjusted independently. Sounds are generated by ArcSonare’s local sound engine."
      className="sound-card-events"
    >
      <div className="event-sounds-columns">
        <div className="event-sounds-column">{renderCol(left)}</div>
        <div className="event-sounds-column">{renderCol(right)}</div>
      </div>
    </SoundSettingsCard>
  );
}
