export function builtinBackgroundSrc(id: string): string | undefined {
  return BACKGROUND_LIBRARY.find((option) => option.id === id)?.src;
}

export function resolveBackgroundSrc(
  customBackgroundPath: string,
  convertFileSrc: (path: string) => string,
): string | undefined {
  if (!customBackgroundPath) return undefined;
  if (customBackgroundPath.startsWith(BUILTIN_BACKGROUND_PREFIX)) {
    return builtinBackgroundSrc(
      customBackgroundPath.slice(BUILTIN_BACKGROUND_PREFIX.length),
    );
  }
  return convertFileSrc(customBackgroundPath);
}
